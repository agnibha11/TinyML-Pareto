#!/usr/bin/env python3
"""Write the P1/P2/P3 split files from manifest.parquet, with leakage assertions.

Protocols (Agnibha workstream doc, "Split protocols"; CONTRACT.md section 3):

    P1  leaky, 10-class           1 fold   stratified random 70/15/15 of ALL stride-512 windows (overlap kept on
                                           purpose: this reproduces what most CWRU papers report)
    P2  recording-wise, 10-class  4 folds  fold k: test = non-overlapping windows of load k; train = all windows of
                                           the other three loads (minus a stratified 15 % validation carve-out)
    P3  bearing-disjoint, 4-class 3 folds  fold k: held-out fault size s_k in (0.007, 0.014, 0.021). Test = all
                                           IR/B/OR windows of size s_k (non-overlapping) + normal windows of load 3
                                           (non-overlapping). Train = faults of the other two sizes + normal loads 0-2

Validation sets are carved from the training windows (stratified 15 %, fixed random_state per protocol and fold).
They are used only for early stopping and are never reported.

Outputs:
    splits/<P>/<fold>/{train,val,test}.npy   int32 window ids (git-ignored, regenerated by this script)
    splits/README.md                          the protocol table and per-split class counts (committed)
    results/split_counts.csv                  one row per (protocol, fold, set, class)

Usage:
    python ml/splits.py            # write all splits, then run the checks
    python ml/splits.py --check    # re-run the assertions on existing files only
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split

REPO = Path(__file__).resolve().parents[1]
WIN = 1024
SIZES = (0.007, 0.014, 0.021)
VAL_FRAC = 0.15
PROTOCOLS = {"P1": 1, "P2": 4, "P3": 3}          # number of folds
LABEL = {"P1": "class10", "P2": "class10", "P3": "class4"}
SPLIT_SEED = 20261012                             # fixed: splits never depend on the training seed


def load_manifest(processed: Path) -> pd.DataFrame:
    m = pd.read_parquet(processed / "manifest.parquet")
    m["nonoverlap"] = (m.start_idx % WIN == 0)
    return m


def _carve_val(train_ids: np.ndarray, labels: np.ndarray, rs: int) -> tuple[np.ndarray, np.ndarray]:
    tr, va = train_test_split(train_ids, test_size=VAL_FRAC, stratify=labels, random_state=rs)
    return np.sort(tr), np.sort(va)


def make_splits(m: pd.DataFrame) -> dict[tuple[str, int], dict[str, np.ndarray]]:
    out: dict[tuple[str, int], dict[str, np.ndarray]] = {}
    ids = m.window_id.to_numpy()

    # P1 - leaky
    trv, te = train_test_split(ids, test_size=0.15, stratify=m.class10, random_state=SPLIT_SEED)
    lab = m.set_index("window_id").class10
    tr, va = train_test_split(trv, test_size=0.15 / 0.85, stratify=lab.loc[trv], random_state=SPLIT_SEED)
    out[("P1", 0)] = {"train": np.sort(tr), "val": np.sort(va), "test": np.sort(te)}

    # P2 - leave one load out
    for k in range(4):
        test = m[(m.load_hp == k) & m.nonoverlap].window_id.to_numpy()
        trn = m[m.load_hp != k]
        tr, va = _carve_val(trn.window_id.to_numpy(), trn.class10.to_numpy(), SPLIT_SEED + 100 + k)
        out[("P2", k)] = {"train": tr, "val": va, "test": np.sort(test)}

    # P3 - leave one fault size out (faults), leave load 3 out (normal: one physical bearing only)
    fault = m.fault_type != "N"
    for k, s in enumerate(SIZES):
        is_s = np.isclose(m.fault_size_in, s)
        test = m[((fault & is_s) | (~fault & (m.load_hp == 3))) & m.nonoverlap].window_id.to_numpy()
        trn = m[(fault & ~is_s) | (~fault & (m.load_hp != 3))]
        tr, va = _carve_val(trn.window_id.to_numpy(), trn.class4.to_numpy(), SPLIT_SEED + 200 + k)
        out[("P3", k)] = {"train": tr, "val": va, "test": np.sort(test)}
    return out


def split_dir(root: Path, p: str, k: int) -> Path:
    return root / p / str(k)


def write(splits, root: Path) -> None:
    for (p, k), sets in splits.items():
        d = split_dir(root, p, k)
        d.mkdir(parents=True, exist_ok=True)
        for name, a in sets.items():
            np.save(d / f"{name}.npy", a.astype(np.int32))


def read(root: Path) -> dict[tuple[str, int], dict[str, np.ndarray]]:
    out = {}
    for p, n in PROTOCOLS.items():
        for k in range(n):
            d = split_dir(root, p, k)
            out[(p, k)] = {s: np.load(d / f"{s}.npy") for s in ("train", "val", "test")}
    return out


def load_split(p: str, k: int, root: Path = REPO / "splits") -> dict[str, np.ndarray]:
    """Public helper for train.py / evaluate.py."""
    d = split_dir(root, p, k)
    return {s: np.load(d / f"{s}.npy") for s in ("train", "val", "test")}


def overlap_fraction(m: pd.DataFrame, test: np.ndarray, train: np.ndarray) -> float:
    """Fraction of test windows that share at least one sample with some training window (same file)."""
    mi = m.set_index("window_id")
    tr = mi.loc[train, ["file_id", "start_idx"]]
    starts = {f: np.sort(g.start_idx.to_numpy()) for f, g in tr.groupby("file_id")}
    hit = 0
    for f, s in mi.loc[test, ["file_id", "start_idx"]].itertuples(index=False):
        a = starts.get(f)
        if a is None:
            continue
        j = np.searchsorted(a, s)
        near = a[max(0, j - 2):j + 2]
        hit += bool(np.any(np.abs(near - s) < WIN))
    return hit / len(test)


def check(m: pd.DataFrame, splits) -> pd.DataFrame:
    mi = m.set_index("window_id")
    problems, rows, leak = [], [], {}
    for (p, k), sets in splits.items():
        lab = LABEL[p]
        n_cls = 10 if lab == "class10" else 4
        tr, va, te = (set(sets[s].tolist()) for s in ("train", "val", "test"))
        if tr & va or tr & te or va & te:
            problems.append(f"{p}/{k}: a window_id is in two sets")
        if p in ("P2", "P3"):
            if not mi.loc[sets["test"], "nonoverlap"].all():
                problems.append(f"{p}/{k}: overlapping window in the test set")
            ftr = set(mi.loc[sets["train"]].file_id) | set(mi.loc[sets["val"]].file_id)
            fte = set(mi.loc[sets["test"]].file_id)
            if ftr & fte:
                problems.append(f"{p}/{k}: files {sorted(ftr & fte)} in both train and test")
        if p == "P3":
            def pairs(ids):
                d = mi.loc[ids]
                d = d[d.fault_type != "N"]
                return set(zip(d.fault_type, d.fault_size_in.round(3)))
            shared = (pairs(sets["train"]) | pairs(sets["val"])) & pairs(sets["test"])
            if shared:
                problems.append(f"P3/{k}: fault bearings {sorted(shared)} in both train and test")
            if len(set(mi.loc[sets["test"]].fault_size_in.round(3)) - {0.0}) != 1:
                problems.append(f"P3/{k}: test set must hold exactly one fault size")
        for s in ("train", "val", "test"):
            c = mi.loc[sets[s], lab].value_counts().reindex(range(n_cls), fill_value=0)
            if s != "val" and (c == 0).any():
                problems.append(f"{p}/{k}/{s}: classes {c[c == 0].index.tolist()} missing")
            for cls, n in c.items():
                rows.append(dict(protocol=p, fold=k, set=s, label=lab, cls=int(cls), n=int(n)))
        leak[(p, k)] = overlap_fraction(m, sets["test"], np.concatenate([sets["train"], sets["val"]]))
        if p != "P1" and leak[(p, k)] > 0:
            problems.append(f"{p}/{k}: {leak[(p, k)]:.1%} of test windows share samples with training windows")
    if problems:
        sys.exit("SPLIT CHECK FAILED:\n  - " + "\n  - ".join(problems))
    df = pd.DataFrame(rows)
    for (p, k), f in leak.items():
        print(f"  {p} fold {k}: train {len(splits[(p, k)]['train']):5d}  val {len(splits[(p, k)]['val']):4d}  "
              f"test {len(splits[(p, k)]['test']):5d}   test windows sharing samples with train: {f:6.1%}")
    df.attrs["leak"] = leak
    print(f"SPLIT CHECK OK: {len(splits)} splits; P2/P3 test sets are non-overlapping and file-/bearing-disjoint.")
    return df


def write_readme(df: pd.DataFrame, splits, root: Path) -> None:
    names10 = [c["name"] for c in json.loads((REPO / "handoff" / "classes.json").read_text())["class10"]]
    names4 = ["N", "IR", "B", "OR"]
    lines = [
        "# splits/ — generated by `ml/splits.py` (never edit by hand)", "",
        "The `.npy` files hold `window_id`s into `data/processed/windows.npy` and are git-ignored; "
        "`python ml/splits.py` regenerates them bit-for-bit (fixed `random_state`).", "",
        "| Protocol | Task | Folds | Train | Test | Validation |", "|---|---|---|---|---|---|",
        "| P1 leaky | 10-class | 1 | random stratified 70 % of all stride-512 windows | random 15 % (overlaps train) "
        "| random 15 % |",
        "| P2 recording-wise | 10-class | 4 (leave one load out) | all windows of the other 3 loads | non-overlapping "
        "windows of the held-out load | stratified 15 % of train |",
        "| P3 bearing-disjoint | 4-class | 3 (leave one fault size out) | faults of the other 2 sizes + normal loads 0–2 "
        "| faults of the held-out size + normal load 3 (non-overlapping) | stratified 15 % of train |", "",
        "Checks (`python ml/splits.py --check`): no window in two sets; P2/P3 test windows non-overlapping; "
        "no CWRU file in both train and test (P2, P3); no (fault type, fault size) bearing in both train and test (P3); "
        "every class present in every train and test set; P2/P3 test windows share no samples with training windows.",
        "", "## Sizes", "", "| split | train | val | test | test windows sharing samples with train |",
        "|---|---|---|---|---|"]
    for (p, k), s in splits.items():
        lines.append(f"| {p}/{k} | {len(s['train'])} | {len(s['val'])} | {len(s['test'])} | "
                     f"{df.attrs['leak'][(p, k)]:.1%} |")
    lines += ["", "## Test-set class counts", ""]
    for p in PROTOCOLS:
        names = names4 if LABEL[p] == "class4" else names10
        sub = df[(df.protocol == p) & (df.set == "test")].pivot(index="fold", columns="cls", values="n")
        lines.append(f"**{p}** (" + LABEL[p] + ")")
        lines.append("")
        lines.append("| fold | " + " | ".join(names) + " |")
        lines.append("|---|" + "---|" * len(names))
        for fold, r in sub.iterrows():
            lines.append(f"| {fold} | " + " | ".join(str(int(v)) for v in r.values) + " |")
        lines.append("")
    lines += ["P3 fold k holds out fault size 0.007 / 0.014 / 0.021 in (k = 0 / 1 / 2). The normal class has a single "
              "physical bearing, so in P3 it is split by load (train 0–2 HP, test 3 HP); this is a stated limitation.",
              ""]
    (root / "README.md").write_text("\n".join(lines))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--processed", type=Path, default=REPO / "data" / "processed")
    ap.add_argument("--out", type=Path, default=REPO / "splits")
    a = ap.parse_args()
    m = load_manifest(a.processed)
    if a.check:
        check(m, read(a.out))
        return
    s = make_splits(m)
    write(s, a.out)
    df = check(m, read(a.out))
    df.to_csv(REPO / "results" / "split_counts.csv", index=False)
    write_readme(df, s, a.out)
    print(f"wrote {a.out}/<P>/<fold>/{{train,val,test}}.npy, {a.out}/README.md, results/split_counts.csv")


if __name__ == "__main__":
    main()

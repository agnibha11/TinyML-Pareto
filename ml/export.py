import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import features as FE  # noqa: E402
import models as MD  # noqa: E402
from splits import load_split  # noqa: E402
from tools.contract import REGISTRY_COLUMNS, c_name, parse_model_id  # noqa: E402
from train import DEPLOY, rf_hard_predict, tflite_predict  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
HANDOFF = REPO / "handoff"
TV = HANDOFF / "test_vectors"
MODELS = REPO / "models"
CONFIGS = REPO / "configs"
MAX_ARRAY_B = 900 * 1024
N_PER_CLASS = 10


def c_floats(a, per_line=6, indent="    ") -> str:
    vals = [f"{float(v):.9e}f" for v in np.asarray(a, dtype=np.float32).ravel()]
    return "\n".join(indent + ", ".join(vals[i:i + per_line]) + "," for i in range(0, len(vals), per_line))


# ------------------------------------------------------------------------------------------------------------------
def norm_constants(split) -> dict[str, np.ndarray]:
    W = FE.windows()
    tr = split["train"]
    r0 = FE.R0Norm.fit(W[tr])
    out = {"r0_mu": np.float32(r0.mu), "r0_sigma": np.float32(r0.sigma)}
    for rep in ("r1", "r2", "r3", "r4"):
        n = FE.Normalizer.fit(FE.cached(rep)[tr])
        out[f"{rep}_mean"], out[f"{rep}_std"] = n.mean, n.std
    return out


def write_norm(nc: dict) -> None:
    np.savez(HANDOFF / "norm_constants.npz", **nc)
    lines = ["// norm_constants.h - GENERATED by ml/export.py; do not edit.",
             "// Training statistics of P2 fold 0 (the deployed instances), handoff/features_spec.md.",
             "#pragma once", "",
             f"static const float g_r0_mu = {float(nc['r0_mu']):.9e}f;",
             f"static const float g_r0_sigma = {float(nc['r0_sigma']):.9e}f;", ""]
    for rep, n in (("r1", 10), ("r2", 24), ("r3", 256), ("r4", 41)):
        for k in ("mean", "std"):
            lines += [f"static const float g_{rep}_{k}[{n}] = {{", c_floats(nc[f"{rep}_{k}"]), "};", ""]
    (HANDOFF / "norm_constants.h").write_text("\n".join(lines))


def test_vector_ids(split, manifest) -> np.ndarray:
    te = manifest.set_index("window_id").loc[split["test"]]
    ids = []
    for c in range(10):
        cand = np.sort(te[te.class10 == c].index.to_numpy())
        pick = cand[np.linspace(0, len(cand) - 1, N_PER_CLASS).round().astype(int)]
        ids += pick.tolist()
    return np.array(ids, dtype=np.int32)


def write_test_vectors(ids, nc) -> dict[str, np.ndarray]:
    TV.mkdir(parents=True, exist_ok=True)
    raw = np.asarray(FE.windows()[ids], dtype=np.float32)
    tv = {"ids": ids, "raw": raw,
          "r0_norm": FE.R0Norm(float(nc["r0_mu"]), float(nc["r0_sigma"]))(raw)}
    for rep in ("r1", "r2", "r3", "r4"):
        F = FE.compute(rep, raw)
        tv[rep] = F
        tv[f"{rep}_norm"] = FE.Normalizer(nc[f"{rep}_mean"], nc[f"{rep}_std"])(F)
    for k, v in tv.items():
        np.save(TV / f"{k}.npy", v)
    return tv


# ------------------------------------------------------------------------------------------------------------------
def tflite_ops(blob: bytes) -> list[str]:
    import tensorflow as tf
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        tf.lite.experimental.Analyzer.analyze(model_content=blob)
    return sorted(set(re.findall(r"Op#\d+ (\w+)", buf.getvalue())))


def tflite_qparams(blob: bytes) -> tuple:
    import tensorflow as tf
    it = tf.lite.Interpreter(model_content=blob)
    i, o = it.get_input_details()[0], it.get_output_details()[0]
    if i["dtype"] == np.int8:
        return (float(i["quantization"][0]), int(i["quantization"][1]), float(o["quantization"][0]),
                int(o["quantization"][1]))
    return ("", "", "", "")


def c_array(name: str, blob: bytes, model_id: str) -> str:
    hexes = [f"0x{b:02x}" for b in blob]
    body = "\n".join("  " + ", ".join(hexes[i:i + 16]) + "," for i in range(0, len(hexes), 16))
    return (f"// model.h - GENERATED by ml/export.py from models/{model_id}/model.tflite; do not edit.\n"
            "#pragma once\n#include <stdalign.h>\n\n"
            f"alignas(16) const unsigned char g_model_{name}[] = {{\n{body}\n}};\n"
            f"const unsigned int g_model_{name}_len = {len(blob)};\n")


def export_tree(mid: str, arch: MD.Arch, tv) -> dict | None:
    import emlearn
    import joblib
    src = DEPLOY / f"{arch.key}.joblib"
    if not src.exists():
        return None
    d = joblib.load(src)
    est = d["estimator"]
    out = MODELS / mid
    out.mkdir(parents=True, exist_ok=True)
    name = c_name(mid)
    emlearn.convert(est, method="inline", dtype="float").save(file=str(out / "model.h"), name=name)
    h = (out / "model.h").read_text()
    if f"{name}_predict(const float" not in h:
        sys.exit(f"{mid}: emlearn header has no float predict function")
    X = tv[f"{arch.rep}_norm"]
    yp = est.predict(X) if arch.family == "dt" else rf_hard_predict(est, X)   # the rule the C code implements
    onehot = np.eye(10, dtype=np.float32)[yp]
    if arch.family == "dt":
        params = int(est.tree_.node_count)
        depth = int(est.get_depth())
    else:
        params = int(sum(e.tree_.node_count for e in est.estimators_))
        depth = int(max(e.get_depth() for e in est.estimators_))
    return {"runtime": "emlearn", "params": params, "macs": 0, "ops": "", "q": ("", "", "", ""),
            "artifact": f"models/{mid}/model.h", "outputs": onehot, "array_B": 0, "extra": {"max_depth_fit": depth}}


def export_nn(mid: str, arch: MD.Arch, prec: str, tv) -> dict | None:
    src_prec = "int8" if prec == "int8ref" else prec
    src = DEPLOY / f"{arch.key}-{src_prec}.tflite"
    if not src.exists():
        return None
    blob = src.read_bytes()
    out = MODELS / mid
    out.mkdir(parents=True, exist_ok=True)
    (out / "model.tflite").write_bytes(blob)
    (out / "model.h").write_text(c_array(c_name(mid), blob, mid))
    X = tv["r0_norm"] if arch.rep == "r0" else tv[f"{arch.rep}_norm"]
    _, O = tflite_predict(blob, X, ref=True)          # TFLM-equivalent arithmetic (VERIFY reference)
    n_in = 1024 if arch.rep == "r0" else FE.N_FEAT[arch.rep]
    params, macs = MD.nn_cost(arch, 10, n_in)
    return {"runtime": "tflm-ref" if prec == "int8ref" else "tflm-cmsis", "params": params, "macs": macs,
            "ops": ";".join(tflite_ops(blob)), "q": tflite_qparams(blob), "artifact": f"models/{mid}/model.tflite",
            "outputs": O.astype(np.float32), "array_B": len(blob), "extra": {}}


def write_config(mid: str, arch: MD.Arch) -> None:
    import yaml
    from train import BATCH, EPOCHS, LR, PATIENCE, QAT_EPOCHS, QAT_LR, N_REP
    tok = parse_model_id(mid)
    cfg = {"model_id": mid, **tok, "hyperparameters": {k: (list(v) if isinstance(v, tuple) else v)
                                                       for k, v in arch.hp.items()}}
    if arch.family == "cnn":
        cfg["hyperparameters"]["filters"] = MD.cnn_filters(arch.hp["width"], arch.hp["blocks"])
        cfg["architecture"] = ("Conv2D(k x 1) over (1024,1,1): block 1 kernel 9 stride 2, blocks 2.. kernel 3; "
                               "each block Conv -> BatchNorm -> ReLU -> MaxPool(2); GAP -> Dense -> Softmax")
    if arch.is_nn:
        cfg["training"] = {"optimizer": "adam", "lr": LR, "batch": BATCH, "max_epochs": EPOCHS,
                           "early_stopping": {"monitor": "val_loss", "patience": PATIENCE, "restore_best": True}}
        if tok["precision"] in ("int8", "int8ref", "int8qat"):
            cfg["quantization"] = {"type": "full-int8", "representative_windows": N_REP}
        if tok["precision"] == "int8qat":
            cfg["quantization"].update(qat_epochs=QAT_EPOCHS, qat_lr=QAT_LR)
    else:
        cfg["training"] = {"library": "scikit-learn 1.5.2", "criterion": "gini"}
    cfg["seeds"] = [0, 1, 2, 3, 4]
    cfg["deployed_instance"] = {"protocol": "P2", "fold": 0, "seed": 0}
    CONFIGS.mkdir(exist_ok=True)
    (CONFIGS / f"{mid}.yaml").write_text(yaml.safe_dump(cfg, sort_keys=False))


def main() -> None:
    manifest = pd.read_parquet(REPO / "data" / "processed" / "manifest.parquet")
    split = load_split("P2", 0)
    nc = norm_constants(split)
    write_norm(nc)
    ids = test_vector_ids(split, manifest)
    tv = write_test_vectors(ids, nc)
    (TV / "outputs").mkdir(parents=True, exist_ok=True)

    rows, ops_union, missing = [], set(), []
    for arch in MD.all_archs():
        for mid in arch.model_ids:
            write_config(mid, arch)
            prec = mid.rsplit("-", 1)[1]
            r = export_tree(mid, arch, tv) if not arch.is_nn else export_nn(mid, arch, prec, tv)
            if r is None:
                missing.append(mid)
                continue
            np.save(TV / "outputs" / f"{mid}.npy", r["outputs"])
            if r["ops"]:
                ops_union |= set(r["ops"].split(";"))
            tok = parse_model_id(mid)
            isc, izp, osc, ozp = r["q"]
            row = {"model_id": mid, **tok, "runtime": r["runtime"], "n_classes": 10, "input_scale": isc,
                   "input_zero_point": izp, "output_scale": osc, "output_zero_point": ozp, "params": r["params"],
                   "macs": r["macs"], "ops": r["ops"], "protocol_trained": "P2", "fold": 0, "seed": 0,
                   "artifact": r["artifact"], "feasible": int(r["array_B"] <= MAX_ARRAY_B)}
            rows.append(row)
            meta = {k: row[k] for k in REGISTRY_COLUMNS if k not in ("artifact", "feasible")}
            meta.update(r["extra"])
            if r["array_B"]:
                meta["tflite_B"] = r["array_B"]
            (MODELS / mid / "meta.json").write_text(json.dumps(meta, indent=2) + "\n")
    with open(MODELS / "registry.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=REGISTRY_COLUMNS)
        w.writeheader()
        w.writerows(rows)
    if ops_union:
        (HANDOFF / "ops_union.txt").write_text("\n".join(sorted(ops_union)) + "\n")
    print(f"exported {len(rows)} models; missing deployed instance for {len(missing)}: {missing[:8]}"
          f"{' ...' if len(missing) > 8 else ''}")
    print(f"ops union: {sorted(ops_union)}")


if __name__ == "__main__":
    main()

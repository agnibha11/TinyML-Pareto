#!/usr/bin/env python3
"""Build the team's bench firmware (firmware/bench/bench_core.cpp, unmodified) for the PC with REAL models:
emlearn trees, TFLM MLPs/CNNs (x86, reference kernels) and the C front end (tools/vmcu/fw/frontend.c).

The result, build/host/bench_sim_models, is a simulated board behind a pseudo-terminal that speaks the CONTRACT.md
serial protocol, so tools/dut.py drives it exactly like the Nano. tools/demo_sim.py uses it for the M4-style dry run
(SEL every model, VERIFY the 100 test vectors, compare with the host outputs). Timing on the PC is meaningless; the
cycle numbers come from the virtual Cortex-M4 (run_vmcu.py) and later from the board.

Usage: python tools/vmcu/host_bundle.py --deps <deps dir> [--models <model_id> ...]
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))
from tools.contract import c_name  # noqa: E402

FW = REPO / "tools" / "vmcu" / "fw"
BENCH = REPO / "firmware" / "bench"
SIM = REPO / "firmware" / "tests" / "host_sim"
OUT = REPO / "build" / "host"
N_FEAT = {"r0": 1024, "r1": 10, "r2": 24, "r3": 256, "r4": 41}

FE_WRAPPERS = """
static void fe_rep0(const float *x, float *f) { fe_r0(x, g_r0_mu, g_r0_sigma, f); }
static void fe_rep1(const float *x, float *f) { fe_r1(x, f); fe_zscore(f, g_r1_mean, g_r1_std, 10); }
static void fe_rep2(const float *x, float *f) { fe_r2(x, f); fe_zscore(f, g_r2_mean, g_r2_std, 24); }
static void fe_rep3(const float *x, float *f) { fe_r3(x, f); fe_zscore(f, g_r3_mean, g_r3_std, 256); }
static void fe_rep4(const float *x, float *f) { fe_r4(x, f); fe_zscore(f, g_r4_mean, g_r4_std, 41); }
static int s_last = 0;
static int tree_outputs(float *o, int n) { int m = n < 10 ? n : 10; for (int i = 0; i < m; ++i) o[i] = i == s_last; return m; }
static int s_fe_ready = 0;
static void fe_ready(void) { if (!s_fe_ready) { fe_init(); s_fe_ready = 1; } }
"""


def generate(reg: pd.DataFrame) -> Path:
    inc, funcs, rows = [], [], []
    for k, r in enumerate(reg.itertuples(index=False)):
        cn = c_name(r.model_id)
        inc.append(f'#include "{REPO / "models" / r.model_id / "model.h"}"')
        fe = f"fe_rep{r.input_rep[1]}"
        if r.runtime == "emlearn":
            funcs.append(f"static int setup_{k}(uint32_t *u) {{ fe_ready(); *u = 0; return 0; }}\n"
                         f"static int infer_{k}(const float *f, int *c) {{ *c = (int){cn}_predict(f, "
                         f"{N_FEAT[r.input_rep]}); s_last = *c; return 0; }}")
            rows.append(f'  {{"{r.model_id}", "emlearn", setup_{k}, {fe}, infer_{k}, tree_outputs}},')
        else:
            funcs.append(f"static int setup_{k}(uint32_t *u) {{ fe_ready(); return bench_tflm_setup(g_model_{cn}, u); }}")
            rows.append(f'  {{"{r.model_id}", "tflm-host", setup_{k}, {fe}, bench_tflm_infer, bench_tflm_outputs}},')
    src = ["// GENERATED by tools/vmcu/host_bundle.py; do not edit.", "#include <stdint.h>", '#include "bench_core.h"',
           '#include "frontend.h"', '#include "norm_constants.h"', '#include "tflm_glue.h"', *inc, FE_WRAPPERS, *funcs,
           "const bench_model_t g_models[] = {", *rows, "};",
           "const int g_n_models = (int)(sizeof g_models / sizeof g_models[0]);", ""]
    OUT.mkdir(parents=True, exist_ok=True)
    p = OUT / "bundle_host.cpp"
    p.write_text("\n".join(src))
    return p


def build(bundle: Path, deps: Path) -> Path:
    import emlearn
    tflm, fb = deps / "tflite-micro", deps / "flatbuffers" / "include"
    dsp, core = deps / "CMSIS-DSP", deps / "CMSIS_6" / "CMSIS" / "Core" / "Include"
    inc = [BENCH, FW, REPO / "handoff", tflm, fb, core, dsp / "Include", dsp / "PrivateInclude", emlearn.includedir]
    I = [f"-I{p}" for p in inc]
    defs = ["-DBUNDLE_ID=1", '-DBENCH_GIT_HASH="sim-models"', "-DFLATBUFFERS_LOCALE_INDEPENDENT=0",
            "-DTF_LITE_DISABLE_X86_NEON", "-DTFLM_REMOVE_VIRTUAL_DELETE", "-D__GNUC_PYTHON__", "-DTF_LITE_USE_CTIME"]
    objs = []
    for src, cxx in ((BENCH / "bench_core.cpp", True), (BENCH / "stored_inputs.cpp", True),
                     (SIM / "host_hal.cpp", True), (SIM / "main.cpp", True), (bundle, True),
                     (BENCH / "tflm_glue.cpp", True), (BENCH / "frontend.c", False)):
        o = OUT / (src.stem + ".o")
        cc = ["g++", "-std=c++17", "-fno-rtti", "-fno-exceptions"] if cxx else ["gcc", "-std=c11"]
        r = subprocess.run([*cc, "-O2", *defs, *I, "-w", "-c", str(src), "-o", str(o)], capture_output=True, text=True)
        if r.returncode:
            sys.exit(f"compile {src.name} failed:\n{r.stderr[-3000:]}")
        objs.append(o)
    exe = OUT / "bench_sim_models"
    r = subprocess.run(["g++", *map(str, objs), str(OUT / "lib" / "libtflm.a"), str(OUT / "lib" / "libcmsisdsp.a"),
                        "-lm", "-o", str(exe)], capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"link failed:\n{r.stderr[-3000:]}")
    return exe


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--deps", type=Path, required=True)
    ap.add_argument("--models", nargs="*")
    a = ap.parse_args()
    reg = pd.read_csv(REPO / "models" / "registry.csv", keep_default_na=False)
    reg = reg[reg.runtime != "tflm-ref"]                       # same .tflite as int8; PC build has one kernel set
    if a.models:
        reg = reg[reg.model_id.isin(a.models)]
    exe = build(generate(reg), a.deps)
    print(f"built {exe} with {len(reg)} models")


if __name__ == "__main__":
    main()

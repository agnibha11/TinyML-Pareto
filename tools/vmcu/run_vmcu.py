#!/usr/bin/env python3
"""Virtual-MCU campaign: build every deployed model into Cortex-M4F images, run them in QEMU (mps2-an386) with the
vmcount plugin, and write pre-hardware latency, memory, VERIFY-agreement and feature-parity results.

Images (one ELF each):
    trees   all emlearn models + the M2 feature-parity dump      (runtime emlearn)
    cmsis   all NN models on TFLM + CMSIS-NN kernels              (runtime tflm-cmsis)
    ref     the int8 CNNs on TFLM reference kernels               (runtime tflm-ref, the kernel ablation)

Outputs:
    results/vmcu/vmcu_metrics.csv     one row per model_id: flash, arena, stack, front-end and inference
                                      instructions/cycles (median of 5 stored windows), VERIFY agreement
    results/vmcu/vmcu_parity.csv      C front end vs ml/features.py on the 100 test vectors (gate M2)
    results/vmcu/vmcu_footprint.csv   per-image code/data attribution (TFLM, CMSIS-DSP, front end, models, libc)
    results/vmcu/<image>_regions.csv  every measured region (model, phase, stored window, insn, cycles, ...)
Latency estimate = estimated cycles / 64 MHz. These are emulator numbers, to be calibrated against DWT on the board.

Usage: python tools/vmcu/run_vmcu.py --deps <deps dir> --plugin <libvmcount.so> [--images trees cmsis ref]
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import subprocess
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))
from tools.contract import c_name  # noqa: E402

FW = REPO / "tools" / "vmcu" / "fw"
BENCH = REPO / "firmware" / "bench"
BUILD = REPO / "build" / "vmcu"
OUT = REPO / "results" / "vmcu"
TV = REPO / "handoff" / "test_vectors"
F_CPU = 64e6
ARCH = ["-mcpu=cortex-m4", "-mthumb", "-mfpu=fpv4-sp-d16", "-mfloat-abi=softfp"]   # as the mbed_nano core
REP_INDEX = {"r0": 0, "r1": 1, "r2": 2, "r3": 3, "r4": 4}
N_FEAT = {"r0": 1024, "r1": 10, "r2": 24, "r3": 256, "r4": 42}


def c_floats(a: np.ndarray) -> str:
    vals = [f"{float(v):.9e}f" for v in np.asarray(a, np.float32).ravel()]
    return ",\n".join(", ".join(vals[i:i + 8]) for i in range(0, len(vals), 8))


def write_inputs(gen: Path) -> None:
    stored = np.load(TV / "stored_inputs.npy").astype(np.float32)
    raw = np.load(TV / "raw.npy").astype(np.float32)
    rows = lambda A: ",\n".join("{" + c_floats(r) + "}" for r in A)  # noqa: E731
    (gen / "vm_inputs.h").write_text(
        "// GENERATED by tools/vmcu/run_vmcu.py from handoff/test_vectors; do not edit.\n#pragma once\n"
        f"#define VM_N_STORED {len(stored)}\n#define VM_N_TV {len(raw)}\n"
        f"static const float g_vm_stored[{len(stored)}][1024] = {{\n{rows(stored)}\n}};\n"
        f"static const float g_vm_tv[{len(raw)}][1024] = {{\n{rows(raw)}\n}};\n")


def write_bundle(gen: Path, reg: pd.DataFrame, parity: bool) -> None:
    inc, funcs, table = [], [], []
    for k, r in enumerate(reg.itertuples(index=False)):
        cn = c_name(r.model_id)
        rep = REP_INDEX[r.input_rep]
        if r.runtime == "emlearn":
            inc.append(f'#include "{REPO / "models" / r.model_id / "model.h"}"')
            funcs.append(
                f"static int setup_{k}(uint32_t *u) {{ *u = 0; return 0; }}\n"
                f"static int infer_{k}(const float *f, int *c) {{ *c = (int){cn}_predict(f, {N_FEAT[r.input_rep]}); "
                f"s_last = *c; return 0; }}\n")
            table.append(f'  {{"{r.model_id}", "emlearn", {rep}, setup_{k}, infer_{k}, tree_outputs}},')
        else:
            inc.append(f'#include "{REPO / "models" / r.model_id / "model.h"}"')
            funcs.append(f"static int setup_{k}(uint32_t *u) {{ return bench_tflm_setup(g_model_{cn}, u); }}\n")
            table.append(f'  {{"{r.model_id}", "{r.runtime}", {rep}, setup_{k}, bench_tflm_infer, bench_tflm_outputs}},')
    src = ["// GENERATED by tools/vmcu/run_vmcu.py; do not edit.", "#include <stdint.h>", '#include "vm_model.h"',
           *inc, "", "static int s_last = 0;",
           "static int tree_outputs(float *o, int n) { int m = n < 10 ? n : 10; "
           "for (int i = 0; i < m; ++i) o[i] = (i == s_last) ? 1.0f : 0.0f; return m; }", "", *funcs,
           "const vm_model_t g_vm_models[] = {", *table, "};",
           f"const int g_vm_n_models = {len(reg)};", f"const int g_vm_emit_parity = {int(parity)};", ""]
    (gen / "bundle_gen.cc").write_text("\n".join(src))


def build(image: str, reg: pd.DataFrame, deps: Path, parity: bool) -> Path:
    gen = BUILD / image
    gen.mkdir(parents=True, exist_ok=True)
    write_inputs(gen)
    write_bundle(gen, reg, parity)
    import emlearn
    tflm, fb = deps / "tflite-micro", deps / "flatbuffers" / "include"
    core, dsp = deps / "CMSIS_6" / "CMSIS" / "Core" / "Include", deps / "CMSIS-DSP"
    inc = [FW, BENCH, gen, REPO / "handoff", tflm, fb, core, dsp / "Include", dsp / "PrivateInclude", emlearn.includedir]
    I = [f"-I{p}" for p in inc]
    flags = [*ARCH, "-Os", "-ffunction-sections", "-fdata-sections", "-fsigned-char", "-DFLATBUFFERS_LOCALE_INDEPENDENT=0",
             "-DTF_LITE_MCU_DEBUG_LOG", "-DTF_LITE_DISABLE_X86_NEON", "-DTFLM_REMOVE_VIRTUAL_DELETE",
             "-DBENCH_ARENA_ATTR=__attribute__((section(\".psram\")))"]
    srcs = [(FW / "startup.c", "c"), (BENCH / "frontend.c", "c"), (FW / "vbench.cc", "cc"), (gen / "bundle_gen.cc", "cc")]
    libs = [BUILD / "lib" / "libcmsisdsp.a"]
    if image != "trees":
        srcs.append((BENCH / "tflm_glue.cpp", "cc"))
        libs.insert(0, BUILD / "lib" / ("libtflm_cmsis.a" if image == "cmsis" else "libtflm_ref.a"))
    objs = []
    for s, lang in srcs:
        o = gen / (s.stem + ".o")
        cc = ["arm-none-eabi-g++", "-std=c++17", "-fno-rtti", "-fno-exceptions", "-fno-threadsafe-statics"] \
            if lang == "cc" else ["arm-none-eabi-gcc", "-std=c11"]
        r = subprocess.run([*cc, *flags, *I, "-c", str(s), "-o", str(o)], capture_output=True, text=True)
        if r.returncode:
            sys.exit(f"compile {s.name} failed:\n{r.stderr[-4000:]}")
        objs.append(o)
    elf = gen / f"vbench_{image}.elf"
    link = ["arm-none-eabi-g++", *ARCH, "--specs=rdimon.specs", "-T", str(FW / "mps2_an386.ld"), "-Wl,--gc-sections",
            f"-Wl,-Map={gen / 'vbench.map'}", "-Wl,--no-warn-rwx-segments", *map(str, objs), *map(str, libs),
            "-lm", "-o", str(elf)]
    r = subprocess.run(link, capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"link failed:\n{r.stderr[-4000:]}")
    return elf


def symbols(elf: Path) -> dict[str, tuple[int, int]]:
    out = subprocess.run(["arm-none-eabi-nm", "-S", "-C", "--defined-only", str(elf)], capture_output=True,
                         text=True, check=True).stdout
    sym = {}
    for ln in out.splitlines():
        p = ln.split(maxsplit=3)
        if len(p) == 4:
            sym[p[3]] = (int(p[0], 16), int(p[1], 16))
    return sym


def footprint(gen: Path) -> dict[str, int]:
    """Bytes per origin (archive or object) in .text/.rodata (flash) and .data/.bss (RAM), from the map file."""
    txt = (gen / "vbench.map").read_text()
    sizes: dict[str, int] = {}
    pat = re.compile(r"^\s*\.(text|rodata|data|bss)\S*\s+0x([0-9a-f]+)\s+0x([0-9a-f]+)\s+(\S+)", re.M)
    for m in pat.finditer(txt):
        sec, size, origin = m.group(1), int(m.group(3), 16), m.group(4)
        if size == 0:
            continue
        o = Path(origin.split("(")[0]).name
        if "libtflm" in o:
            key = "tflm"
        elif "libcmsisdsp" in o:
            key = "cmsis_dsp"
        elif o in ("libc.a", "libm.a", "libgcc.a", "librdimon.a", "libstdc++.a", "libg.a") or "crt" in o:
            key = "libc"
        elif o == "frontend.o":
            key = "frontend"
        elif o in ("vbench.o",):
            key = "vbench_and_inputs"
        elif o == "bundle_gen.o":
            key = "models"
        elif o == "tflm_glue.o":
            key = "tflm_glue"
        else:
            key = "other"
        flash_ram = "flash" if sec in ("text", "rodata") else "ram"
        sizes[f"{key}_{flash_ram}_B"] = sizes.get(f"{key}_{flash_ram}_B", 0) + size
    return sizes


def run(elf: Path, plugin: Path, timeout_s: int) -> tuple[str, list[dict]]:
    costs = elf.with_suffix(".costs.txt")
    subprocess.run([sys.executable, str(REPO / "tools" / "vmcu" / "cyclemodel.py"), str(elf), str(costs)],
                   check=True, capture_output=True)
    sym = symbols(elf)
    b, e = sym["vm_mark_begin"][0], sym["vm_mark_end"][0]
    log = elf.with_suffix(".vmc.log")
    cmd = ["qemu-system-arm", "-M", "mps2-an386", "-cpu", "cortex-m4", "-nographic", "-monitor", "none",
           "-serial", "none", "-semihosting-config", "enable=on,target=native", "-kernel", str(elf),
           "-plugin", f"{plugin},begin={b:#x},end={e:#x},costs={costs}", "-d", "plugin", "-D", str(log)]
    t0 = time.time()
    r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout_s)
    print(f"  qemu {elf.name}: {time.time() - t0:.0f}s, exit {r.returncode}")
    vmc = []
    for ln in log.read_text().splitlines():
        if ln.startswith("VMC ") and "error" not in ln:
            vmc.append({k: int(v) for k, v in (kv.split("=") for kv in ln.split()[1:])})
    return r.stdout, vmc


def parse(image: str, stdout: str, vmc: list[dict], reg: pd.DataFrame, elf: Path) -> tuple[list, list, list]:
    lines = stdout.splitlines()
    if not any(ln.startswith("VB done") for ln in lines):
        sys.exit(f"{image}: image did not finish:\n" + "\n".join(lines[-20:]))
    labels = [ln.split() for ln in lines if ln.startswith("L ")]
    if len(labels) != len(vmc):
        sys.exit(f"{image}: {len(labels)} labels but {len(vmc)} counter lines")
    regions = [{"image": image, "phase": lab[1], "k": int(lab[2]), "j": int(lab[3]), **c} for lab, c in zip(labels, vmc)]
    R = pd.DataFrame(regions)
    sym = symbols(elf)
    models, k2id = [], {}
    arena, stack, ver = {}, {}, {}
    for ln in lines:
        p = ln.split()
        if p[0] == "M":
            k2id[int(p[1])] = p[2]
        elif p[0] == "A":
            arena[int(p[1])] = (int(p[2]), int(p[3]))
        elif p[0] == "S":
            stack[int(p[1])] = int(p[2])
        elif p[0] == "V":
            ver.setdefault(int(p[1]), []).append((int(p[2]), int(p[3]), np.array(p[4].split(","), float)))
    for k, mid in k2id.items():
        row = reg[reg.model_id == mid].iloc[0]
        cn = c_name(mid)
        if row.runtime == "emlearn":
            flash = sum(sz for n, (_, sz) in sym.items() if n.startswith(cn + "_"))
        else:
            flash = sym.get(f"g_model_{cn}", (0, 0))[1]
        fe = R[(R.k == k) & (R.phase == "FE")]
        inf = R[(R.k == k) & (R.phase == "INF")]
        host = np.load(TV / "outputs" / f"{mid}.npy")
        v = sorted(ver.get(k, []))
        dev_cls = np.array([c for _, c, _ in v])
        dev_out = np.stack([o for *_, o in v]) if v else np.zeros((0, 10))
        host_cls = host.argmax(axis=1)
        tol = (float(row.output_scale) if str(row.output_scale) not in ("", "nan") else 1e-4)
        maxerr = float(np.abs(dev_out - host[:, :dev_out.shape[1]]).max()) if len(v) else float("nan")
        models.append({
            "model_id": mid, "runtime": row.runtime, "image": image, "setup_rc": arena[k][0],
            "flash_model_B": flash, "arena_used_B": arena[k][1], "stack_peak_B": stack.get(k, 0),
            "fe_insn_med": int(fe.insn.median()) if len(fe) else 0, "fe_cyc_med": int(fe.cyc.median()) if len(fe) else 0,
            "inf_insn_med": int(inf.insn.median()) if len(inf) else 0,
            "inf_insn_min": int(inf.insn.min()) if len(inf) else 0, "inf_insn_max": int(inf.insn.max()) if len(inf) else 0,
            "inf_cyc_med": int(inf.cyc.median()) if len(inf) else 0,
            "inf_cyc_min": int(inf.cyc.min()) if len(inf) else 0, "inf_cyc_max": int(inf.cyc.max()) if len(inf) else 0,
            "inf_ld_med": int(inf.ld.median()) if len(inf) else 0, "inf_fp_med": int(inf.fp.median()) if len(inf) else 0,
            "inf_br_med": int(inf.br.median()) if len(inf) else 0, "inf_st_med": int(inf.st.median()) if len(inf) else 0,
            "fe_ld_med": int(fe.ld.median()) if len(fe) else 0, "fe_br_med": int(fe.br.median()) if len(fe) else 0,
            "lat_fe_est_us": round(fe.cyc.median() / F_CPU * 1e6, 2) if len(fe) else 0,
            "lat_inf_est_us": round(inf.cyc.median() / F_CPU * 1e6, 2) if len(inf) else 0,
            "verify_n": len(v), "verify_class_agree": float((dev_cls == host_cls[:len(v)]).mean()) if len(v) else float("nan"),
            "verify_max_abs_err": maxerr, "verify_tol": tol,
            "verify_within_tol": float((np.abs(dev_out - host[:, :dev_out.shape[1]]).max(axis=1) <= tol * 1.0001).mean())
            if len(v) else float("nan")})
    parity = []
    P = {}
    for ln in lines:
        if ln.startswith("P "):
            p = ln.split()
            P.setdefault(int(p[1]), {})[int(p[2])] = np.array(p[3].split(","), float)
        elif ln.startswith("P0ERR"):
            parity.append({"rep": "r0", "n_vectors": 1, "vector": int(ln.split()[1]), "max_abs_err": float(ln.split()[2])})
    for rep, d in P.items():
        ref = np.load(TV / f"r{rep}_norm.npy")
        dev = np.stack([d[i] for i in sorted(d)])
        err = np.abs(dev - ref[:len(dev)])
        parity.append({"rep": f"r{rep}", "n_vectors": len(dev), "vector": -1, "max_abs_err": float(err.max()),
                       "mean_abs_err": float(err.mean()), "worst_feature": int(err.max(axis=0).argmax()),
                       "pass_1e-3": bool(err.max() < 1e-3)})
    return regions, models, parity


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--deps", type=Path, required=True)
    ap.add_argument("--plugin", type=Path, required=True)
    ap.add_argument("--images", nargs="+", default=["trees", "cmsis", "ref"])
    ap.add_argument("--timeout", type=int, default=7000)
    ap.add_argument("--report-only", action="store_true",
                    help="re-print the terminal summary (and results/demo/vmcu_run.svg) from the existing CSVs")
    a = ap.parse_args()
    if a.report_only:
        console_report(pd.read_csv(OUT / "vmcu_metrics.csv"),
                       pd.read_csv(OUT / "vmcu_parity.csv").to_dict("records"), a.images)
        return
    reg = pd.read_csv(REPO / "models" / "registry.csv", keep_default_na=False)
    OUT.mkdir(parents=True, exist_ok=True)
    sel = {"trees": reg[reg.runtime == "emlearn"], "cmsis": reg[reg.runtime == "tflm-cmsis"],
           "ref": reg[reg.runtime == "tflm-ref"]}
    all_models, all_parity, foot = [], [], []
    old = OUT / "vmcu_metrics.csv"
    if old.exists():
        prev = pd.read_csv(old)
        all_models = prev[~prev.image.isin(a.images)].to_dict("records")
    for image in a.images:
        r = sel[image]
        if r.empty:
            print(f"{image}: no models")
            continue
        print(f"{image}: {len(r)} models")
        elf = build(image, r, a.deps, parity=(image == "trees"))
        stdout, vmc = run(elf, a.plugin, a.timeout)
        (BUILD / image / "stdout.txt").write_text(stdout)
        regions, models, parity = parse(image, stdout, vmc, r, elf)
        pd.DataFrame(regions).to_csv(OUT / f"{image}_regions.csv", index=False)
        all_models += models
        if parity:
            pd.DataFrame(parity).to_csv(OUT / "vmcu_parity.csv", index=False)
            all_parity = parity
        fp = footprint(BUILD / image)
        fp["image"] = image
        fp["fe_static_ram_B"] = int(re.search(r"fe_ram=(\d+)", stdout).group(1))
        foot.append(fp)
    pd.DataFrame(all_models).to_csv(OUT / "vmcu_metrics.csv", index=False)
    fprev = OUT / "vmcu_footprint.csv"
    if fprev.exists():
        old_fp = pd.read_csv(fprev)
        foot = old_fp[~old_fp.image.isin(a.images)].to_dict("records") + foot
    pd.DataFrame(foot).to_csv(fprev, index=False)
    M = pd.DataFrame(all_models)
    print(M[["model_id", "flash_model_B", "arena_used_B", "fe_cyc_med", "inf_cyc_med", "verify_class_agree"]]
          .to_string(index=False))
    for p in all_parity:
        print("parity", p)
    console_report(M, all_parity, a.images)


def console_report(M: pd.DataFrame, parity: list, images: list) -> None:
    """Terminal summary, also saved as results/demo/vmcu_run.svg (used on the midsem demo slide)."""
    from rich.console import Console
    from rich.table import Table
    con = Console(record=True, width=132)
    con.print(f"[bold]$ python tools/vmcu/run_vmcu.py --images {' '.join(images)}[/]   "
              "QEMU mps2-an386 (Cortex-M4F) + vmcount plugin, arm-none-eabi-gcc 13.2 -Os, softfp ABI (as the Nano core)")
    t = Table(header_style="bold", title="Deployable models running as Cortex-M4F code (median of 5 stored windows)")
    for c in ("model_id", "runtime", "flash B", "arena B", "stack B", "front end cyc", "inference cyc",
              "latency ms @64MHz", "VERIFY agree"):
        t.add_column(c, justify="left" if c in ("model_id", "runtime") else "right",
                     no_wrap=c == "model_id", min_width=22 if c == "model_id" else None)
    show = M.sort_values(["runtime", "model_id"]).copy()
    # one row per (family, input, precision) group keeps the capture readable; every model is in the CSV
    show["grp"] = show.model_id.str.split("-").str[0] + show.model_id.str.split("-").str[1] + show.model_id.str.split("-").str[3]
    show = show.sort_values("inf_cyc_med").groupby("grp", sort=False).tail(1).sort_values(["runtime", "inf_cyc_med"])
    for r in show.itertuples(index=False):
        t.add_row(r.model_id, r.runtime, f"{r.flash_model_B:,}", f"{r.arena_used_B:,}", f"{r.stack_peak_B:,}",
                  f"{r.fe_cyc_med:,}", f"{r.inf_cyc_med:,}", f"{(r.fe_cyc_med + r.inf_cyc_med) / 64e3:.2f}",
                  f"{r.verify_class_agree:.0%}")
    con.print(t)
    con.print(f"(largest configuration of each family/input/precision group shown; all {len(M)} models in "
              "results/vmcu/vmcu_metrics.csv; VERIFY = class agreement with the host on the 100 test vectors)")
    n_ok = int(((M.verify_class_agree >= 0.99) & (M.verify_within_tol >= 1.0)).sum())
    con.print(f"VERIFY replay: [bold]{n_ok}/{len(M)}[/] models agree with the host on >= 99 % of the vectors, "
              "outputs within one int8 step / 1e-4")
    for p in parity:
        if p.get("vector", -1) == -1:
            con.print(f"M2 parity {p['rep']}: max |C - Python| = {p['max_abs_err']:.2e} on 100 vectors "
                      f"-> {'[green]PASS[/]' if p['max_abs_err'] < 1e-3 else '[red]FAIL[/]'} (gate < 1e-3)")
    out = REPO / "results" / "demo"
    out.mkdir(parents=True, exist_ok=True)
    con.save_svg(str(out / "vmcu_run.svg"), title="tools/vmcu/run_vmcu.py — virtual Cortex-M4")


if __name__ == "__main__":
    main()

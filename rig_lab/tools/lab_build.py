#!/usr/bin/env python3
"""Lab wrappers around tools/bundle.py and tools/build_flash.py that write ONLY inside rig_lab/.

The repo's own tools are imported unchanged; their module-level paths are redirected:
    bundle.py      firmware/bench/...           -> rig_lab/fw/bench/...   (models/bundles.csv -> rig_lab/fw/)
    build_flash.py build/fw/b<k>, results/      -> rig_lab/build/fw/b<k>, rig_lab/results/
    firmware hash  git HEAD                       -> "lab-hfxo" (the lab copy carries the uncommitted HFXO fix)

    python rig_lab/tools/lab_build.py plan                 # generate bundles into rig_lab/fw/bench/models
    python rig_lab/tools/lab_build.py flash 3 /dev/ttyACM0 # compile + upload bundle 3
    python rig_lab/tools/lab_build.py compile 3            # compile only
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

LAB = Path(__file__).resolve().parents[1]
REPO = LAB.parent
sys.path.insert(0, str(REPO))

import pandas as pd  # noqa: E402

import tools.build_flash as F  # noqa: E402
import tools.bundle as B  # noqa: E402

BENCH = LAB / "fw" / "bench"
FW_HASH = "lab-hfxo"


def plan(capacity_kb: int = 600) -> None:
    B.BENCH, B.OUT = BENCH, BENCH / "models"
    reg = pd.read_csv(REPO / "models" / "registry.csv", keep_default_na=False)
    reg = reg[(reg.feasible == 1) & reg.runtime.isin(["emlearn", "tflm-cmsis"])]
    size = B.sizes(reg)
    bundles = B.pack(reg, size, capacity_kb * 1024)
    if B.OUT.exists():
        shutil.rmtree(B.OUT)
    B.OUT.mkdir(parents=True)
    for b in bundles:
        (B.OUT / f"bundle_{b['id']}.h").write_text(B.body(b, reg))
    sel = ["// bundle_gen.cpp - GENERATED by rig_lab/tools/lab_build.py (tools/bundle.py logic).", "#ifdef BUNDLE_ID"]
    for i, b in enumerate(bundles):
        sel += [f"#{'if' if i == 0 else 'elif'} BUNDLE_ID == {b['id']}", f'#include "models/bundle_{b["id"]}.h"']
    sel += ["#else", '#error "unknown BUNDLE_ID"', "#endif", "#endif", ""]
    (BENCH / "bundle_gen.cpp").write_text("\n".join(sel))
    # tools/bundle.py copies only the first two; frontend_fx.c also needs hann_fx.h (repo bug, see rig_lab/README.md)
    for h in ("hann_1024.h", "norm_constants.h", "hann_fx.h"):
        shutil.copy(REPO / "handoff" / h, BENCH / h)
    # handoff/hann_fx.h includes "arm_math_types.h" (CMSIS-DSP >= 1.10); the pinned Arduino_CMSIS-DSP 5.7.0 only has
    # arm_math.h, which defines q15_t/q31_t (repo bug, see rig_lab/README.md)
    fx = BENCH / "hann_fx.h"
    fx.write_text(fx.read_text().replace('#include "arm_math_types.h"', '#include "arm_math.h"'))
    (B.OUT / "bundles.json").write_text(json.dumps(bundles, indent=1))
    rows = [{"bundle": b["id"], "k": k, "model_id": m, "runtime": b["runtime"], "est_flash_model_B": size[m],
             "bundle_arena_B": b["arena_bytes"]} for b in bundles for k, m in enumerate(b["models"])]
    pd.DataFrame(rows).to_csv(LAB / "fw" / "bundles.csv", index=False)
    for b in bundles:
        print(f"bundle {b['id']}: {b['runtime']:<10} {len(b['models']):2d} models {b['model_bytes'] / 1024:7.1f} kB"
              f"  arena {b['arena_bytes'] / 1024:6.1f} kB")


def build(bundle: int, port: str | None) -> None:
    F.REPO, F.SKETCH = LAB, BENCH          # build path -> rig_lab/build/fw, fw_build.csv -> rig_lab/results/
    F.git_hash = lambda: FW_HASH
    (LAB / "results").mkdir(exist_ok=True)
    sys.argv = ["build_flash.py", str(bundle)] + (["--port", port] if port else ["--compile-only"])
    F.main()


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "plan":
        plan()
    elif cmd in ("compile", "flash"):
        build(int(sys.argv[2]), sys.argv[3] if cmd == "flash" else None)
    else:
        sys.exit(__doc__)
